#!/bin/bash
# AfterInstall (new): write wp-config.php from SSM Parameter Store and install the Apache site settings.
# shellcheck source=common.sh
source "$(dirname "$0")/common.sh"

db_name="$(param db_name)"
db_user="$(param db_user)"
db_password="$(param db_password)"
site_url="$(param site_url)"
salts="$(param auth_salts)"

client_flags=""
if [ "$DB_HOST" != "localhost" ]; then
  # Amazon RDS: encrypt the WordPress connection with TLS; keep the RDS CA bundle for verified CLI checks.
  install -d -m 755 "$(dirname "$RDS_CA_FILE")"
  curl -fsSL "$RDS_CA_URL" -o "$RDS_CA_FILE"
  client_flags="define( 'MYSQL_CLIENT_FLAGS', MYSQLI_CLIENT_SSL );"
fi

install -m 644 "$SCRIPT_DIR/../config/a2-wordpress.conf" /etc/httpd/conf.d/a2-wordpress.conf

tmp="$(mktemp)"
cat > "$tmp" <<EOF
<?php
// Generated by configure_wordpress.sh from SSM Parameter Store (${A2_PARAM_PREFIX}/*) on every deployment.
define( 'DB_NAME', '${db_name}' );
define( 'DB_USER', '${db_user}' );
define( 'DB_PASSWORD', '${db_password}' );
define( 'DB_HOST', '${DB_HOST}' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
${client_flags}
${salts}
define( 'WP_HOME', '${site_url}' );
define( 'WP_SITEURL', '${site_url}' );
define( 'DISALLOW_FILE_EDIT', true );
define( 'WP_DEBUG', false );
\$table_prefix = 'wp_';
if ( ! defined( 'ABSPATH' ) ) {
    define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
EOF
install -o root -g apache -m 640 "$tmp" "$WP_DIR/wp-config.php"
rm -f "$tmp"
echo "wp-config.php written for database host ${DB_HOST} and site URL ${site_url}"
